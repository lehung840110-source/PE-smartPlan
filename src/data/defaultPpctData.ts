export function saveStoredPpctData(data: PpctItem[]): void {
  try {
    localStorage.setItem('gdtc_custom_ppct', JSON.stringify(data));
  } catch (e) {
    console.warn(e);
  }
}

export function getStoredPpctData(): PpctItem[] {
  try {
    const saved = localStorage.getItem('gdtc_custom_ppct');
    if (saved) {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed) && parsed.length > 0) return parsed;
    }
  } catch (e) {
    console.warn(e);
  }
  return defaultAllPpctData;
}
